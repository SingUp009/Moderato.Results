static string TypeParams(Op op) => op.Extra.Length > 0 ? $"T, E, {op.Extra}" : "T, E";

static string Return(Op op) => op.Inner.Length > 0 ? $"ValueTask<{op.Inner}>" : "ValueTask";

static string NullChecks(Op op) => string.Concat(op.Delegates.Split(", ", StringSplitOptions.RemoveEmptyEntries)
    .Select(d => $"        ArgumentNullException.ThrowIfNull({d});\n"));

static string ValueTaskReceiver(Op op)
{
    var r = Return(op);
    var call = $"source.Result.{op.Name}({op.Args})";
    string fastPath;
    string core;
    if (op.IsAsync)
    {
        fastPath = $"        if (source.IsCompletedSuccessfully) return {call};\n";
        core = $"=> await (await source.ConfigureAwait(false)).{op.Name}({op.Args}).ConfigureAwait(false);";
    }
    else if (op.Inner.Length > 0)
    {
        fastPath = $"        if (source.IsCompletedSuccessfully) return new {r}({call});\n";
        core = $"=> (await source.ConfigureAwait(false)).{op.Name}({op.Args});";
    }
    else
    {
        fastPath = "        if (source.IsCompletedSuccessfully)\n"
                 + "        {\n"
                 + $"            {call};\n"
                 + "            return default;\n"
                 + "        }\n";
        core = $"=> (await source.ConfigureAwait(false)).{op.Name}({op.Args});";
    }

    return $"\n    /// <summary>{op.Summary}</summary>\n"
         + $"    public static {r} {op.Name}<{TypeParams(op)}>(this ValueTask<Result<T, E>> source, {op.Params})\n"
         + "    {\n"
         + NullChecks(op)
         + fastPath
         + $"        return Core(source, {op.Args});\n"
         + "\n"
         + $"        static async {r} Core(ValueTask<Result<T, E>> source, {op.Params})\n"
         + $"            {core}\n"
         + "    }\n";
}

static string TaskReceiver(Op op)
    => $"\n    /// <summary>{op.Summary}</summary>\n"
     + $"    public static {Return(op)} {op.Name}<{TypeParams(op)}>(this Task<Result<T, E>> source, {op.Params})\n"
     + $"        => new ValueTask<Result<T, E>>(source).{op.Name}({op.Args});\n";

