static string ThisDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;

static void Write(string path, string text)
{
    File.WriteAllText(path, text.Replace("\r\n", "\n"), new UTF8Encoding(false));
    Console.WriteLine($"wrote {path}");
}

static string File_(string summary, string declaration, string body)
{
    var sb = new StringBuilder();
    sb.Append("// <auto-generated>\n");
    sb.Append("// Generated by tools/Generate.cs. Do not edit by hand.\n");
    sb.Append("// </auto-generated>\n");
    sb.Append("#nullable enable\n");
    sb.Append('\n');
    sb.Append("namespace Moderato.Results;\n");
    sb.Append('\n');
    if (summary.Length > 0) sb.Append($"/// <summary>{summary}</summary>\n");
    sb.Append(declaration).Append('\n');
    sb.Append('{').Append(body).Append("}\n");
    return sb.ToString();
}

static string Join(IEnumerable<int> idx, string separator, Func<int, string> f) => string.Join(separator, idx.Select(f));

// ---- Combine / CombineAll (2..8) ----

static string CombineFile()
{
    var body = new StringBuilder();
    for (var n = 2; n <= 8; n++) body.Append(Combine(n)).Append(CombineAll(n));
    return File_("", "public static partial class Result", body.ToString());
}

static string Combine(int n)
{
    var idx = Enumerable.Range(1, n).ToArray();
    var tps = Join(idx, ", ", i => $"T{i}");
    var ps = Join(idx, ", ", i => $"Result<T{i}, E> r{i}");
    var checks = Join(idx, "\n", i => $"        r{i}.ThrowIfDefault();");
    var firstErr = Join(idx, "\n", i => $"        if (r{i}._state == Result<T{i}, E>.StateErr) return new Result<({tps}), E>(new Err<E>(r{i}._error));");
    var values = Join(idx, ", ", i => $"r{i}._value");
    return $"\n    /// <summary>Ok with all values, or the first Err.</summary>\n"
         + $"    public static Result<({tps}), E> Combine<{tps}, E>({ps})\n"
         + "    {\n"
         + $"{checks}\n"
         + $"{firstErr}\n"
         + $"        return new Result<({tps}), E>(new Ok<({tps})>(({values})));\n"
         + "    }\n";
}

static string CombineAll(int n)
{
    var idx = Enumerable.Range(1, n).ToArray();
    var tps = Join(idx, ", ", i => $"T{i}");
    var ps = Join(idx, ", ", i => $"Result<T{i}, E> r{i}");
    var checks = Join(idx, "\n", i => $"        r{i}.ThrowIfDefault();");
    var count = Join(idx, " + ", i => $"(r{i}._state == Result<T{i}, E>.StateErr ? 1 : 0)");
    var collect = Join(idx, "\n", i => $"        if (r{i}._state == Result<T{i}, E>.StateErr) errors[j++] = r{i}._error;");
    var values = Join(idx, ", ", i => $"r{i}._value");
    return $"\n    /// <summary>Ok with all values, or Err with every error.</summary>\n"
         + $"    public static Result<({tps}), E[]> CombineAll<{tps}, E>({ps})\n"
         + "    {\n"
         + $"{checks}\n"
         + $"        var errorCount = {count};\n"
         + $"        if (errorCount == 0) return new Result<({tps}), E[]>(new Ok<({tps})>(({values})));\n"
         + "\n"
         + "        var errors = new E[errorCount];\n"
         + "        var j = 0;\n"
         + $"{collect}\n"
         + $"        return new Result<({tps}), E[]>(new Err<E[]>(errors));\n"
         + "    }\n";
}

// ---- CombineAsync / CombineAllAsync (2..8) ----

static string CombineAsyncFile()
{
    var body = new StringBuilder();
    for (var n = 2; n <= 8; n++)
    {
        body.Append(CombineAsyncValueTask(n, "Combine", "E", "the first Err"));
        body.Append(CombineAsyncTask(n, "Combine", "E", "the first Err"));
        body.Append(CombineAsyncValueTask(n, "CombineAll", "E[]", "Err with every error"));
        body.Append(CombineAsyncTask(n, "CombineAll", "E[]", "Err with every error"));
    }

    return "// <auto-generated>\n"
         + "// Generated by tools/Generate.cs. Do not edit by hand.\n"
         + "// </auto-generated>\n"
         + "#nullable enable\n"
         + "\n"
         + "using System.Runtime.ExceptionServices;\n"
         + "\n"
         + "namespace Moderato.Results;\n"
         + "\n"
         + "public static partial class Result\n"
         + "{" + body + "}\n";
}

static string CombineAsyncValueTask(int n, string name, string error, string summary)
{
    var idx = Enumerable.Range(1, n).ToArray();
    var tps = Join(idx, ", ", i => $"T{i}");
    var ps = Join(idx, ", ", i => $"ValueTask<Result<T{i}, E>> r{i}");
    var locals = Join(idx, ", ", i => $"a{i}");
    var awaits = Join(idx, "\n", i => $"        try {{ a{i} = await r{i}.ConfigureAwait(false); }} catch (Exception ex) {{ error ??= ExceptionDispatchInfo.Capture(ex); }}");
    var decls = Join(idx, "\n", i => $"        Result<T{i}, E> a{i} = default;");
    return $"\n    /// <summary>Awaits every result; Ok with all values, or {summary}.</summary>\n"
         + $"    public static async ValueTask<Result<({tps}), {error}>> {name}Async<{tps}, E>({ps})\n"
         + "    {\n"
         + $"{decls}\n"
         + "        ExceptionDispatchInfo? error = null;\n"
         + $"{awaits}\n"
         + "        error?.Throw();\n"
         + $"        return {name}({locals});\n"
         + "    }\n";
}

static string CombineAsyncTask(int n, string name, string error, string summary)
{
    var idx = Enumerable.Range(1, n).ToArray();
    var tps = Join(idx, ", ", i => $"T{i}");
    var ps = Join(idx, ", ", i => $"Task<Result<T{i}, E>> r{i}");
    var args = Join(idx, ", ", i => $"new ValueTask<Result<T{i}, E>>(r{i})");
    return $"\n    /// <summary>Awaits every result; Ok with all values, or {summary}.</summary>\n"
         + $"    public static ValueTask<Result<({tps}), {error}>> {name}Async<{tps}, E>({ps})\n"
         + $"        => {name}Async({args});\n";
}

