static string LinqAsyncFile()
{
    var body = new StringBuilder();
    body.Append("""

    /// <summary><c>select</c></summary>
    public static ValueTask<Result<U, E>> Select<T, E, U>(this ValueTask<Result<T, E>> source, Func<T, U> selector)
    {
        ArgumentNullException.ThrowIfNull(selector);
        return source.Map(selector);
    }

    /// <summary><c>select</c></summary>
    public static ValueTask<Result<U, E>> Select<T, E, U>(this Task<Result<T, E>> source, Func<T, U> selector)
    {
        ArgumentNullException.ThrowIfNull(selector);
        return source.Map(selector);
    }

""");

    // R = Result, V = ValueTask<Result>, K = Task<Result>; (R, R) is the synchronous ResultLinq.
    foreach (var s in "RVK")
    foreach (var n in "RVK")
    {
        if (s == 'R' && n == 'R') continue;
        body.Append(SelectMany(s, n));
    }

    return File_(
        "LINQ query syntax over any mix of <c>Result</c>, <c>ValueTask&lt;Result&gt;</c> and <c>Task&lt;Result&gt;</c>.",
        "public static class ResultLinqAsync",
        body.ToString());
}

static string SourceType(char kind, string x) => kind switch
{
    'R' => $"Result<{x}, E>",
    'V' => $"ValueTask<Result<{x}, E>>",
    _ => $"Task<Result<{x}, E>>",
};

static string SelectMany(char src, char sel)
{
    var getS = src == 'R' ? "source" : "await source.ConfigureAwait(false)";
    var getN = sel == 'R' ? "selector(t)" : "await selector(t).ConfigureAwait(false)";
    var ps = $"{SourceType(src, "T")} source, Func<T, {SourceType(sel, "U")}> selector, Func<T, U, V> resultSelector";
    return "\n    /// <summary><c>from … from … select</c></summary>\n"
         + "    public static ValueTask<Result<V, E>> SelectMany<T, E, U, V>(\n"
         + $"        this {SourceType(src, "T")} source,\n"
         + $"        Func<T, {SourceType(sel, "U")}> selector,\n"
         + "        Func<T, U, V> resultSelector)\n"
         + "    {\n"
         + "        ArgumentNullException.ThrowIfNull(selector);\n"
         + "        ArgumentNullException.ThrowIfNull(resultSelector);\n"
         + "        return Core(source, selector, resultSelector);\n"
         + "\n"
         + $"        static async ValueTask<Result<V, E>> Core({ps})\n"
         + "        {\n"
         + $"            var s = {getS};\n"
         + "            if (!s.TryGetOk(out var t))\n"
         + "            {\n"
         + "                s.ThrowIfDefault();\n"
         + "                return new Result<V, E>(new Err<E>(s._error));\n"
         + "            }\n"
         + "\n"
         + $"            var n = {getN};\n"
         + "            if (!n.TryGetOk(out var u))\n"
         + "            {\n"
         + "                n.ThrowIfDefault();\n"
         + "                return new Result<V, E>(new Err<E>(n._error));\n"
         + "            }\n"
         + "\n"
         + "            return new Result<V, E>(new Ok<V>(resultSelector(t, u)));\n"
         + "        }\n"
         + "    }\n";
}

